package com.zxyy.qagent.knowledge.controller;

import com.baomidou.mybatisplus.core.metadata.IPage;
import com.zxyy.qagent.knowledge.controller.request.KnowledgeBaseCreateRequest;
import com.zxyy.qagent.knowledge.controller.request.KnowledgeBasePageRequest;
import com.zxyy.qagent.knowledge.controller.vo.KnowledgeBaseVO;
import com.zxyy.qagent.framework.conversion.Result;
import com.zxyy.qagent.framework.web.Results;
import com.zxyy.qagent.knowledge.service.KnowledgeBaseService;
import com.zxyy.qagent.exception.ClientException;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RestController;

/**
 * 知识库控制器
 * 提供知识库的增删改查等基础操作接口
 */
@RestController
@RequiredArgsConstructor
public class KnowledgeBaseController {

    private final KnowledgeBaseService knowledgeBaseService;

    /**
     * 创建知识库
     */
    @PostMapping("/knowledge-base")
    public Result<String> createKnowledgeBase(@RequestBody KnowledgeBaseCreateRequest requestParam) {
        return Results.success(knowledgeBaseService.create(requestParam));
    }

    /**
     * 查询知识库详情
     */
    @GetMapping("/knowledge-base/{kb-id}")
    public Result<KnowledgeBaseVO> queryKnowledgeBase(@PathVariable("kb-id") String kbId) {
        return Results.success(knowledgeBaseService.queryById(kbId));
    }

    /**
     * 分页查询知识库列表
     */
    @GetMapping("/knowledge-base")
    public Result<IPage<KnowledgeBaseVO>> pageQuery(KnowledgeBasePageRequest requestParam) {
        return Results.success(knowledgeBaseService.pageQuery(requestParam));
    }

    @ExceptionHandler(ClientException.class)
    @ResponseStatus(HttpStatus.BAD_REQUEST)
    public Result<Void> handleClientException(ClientException exception) {
        return new Result<Void>().setCode(exception.getErrorCode()).setMessage(exception.getErrorMessage());
    }
}
